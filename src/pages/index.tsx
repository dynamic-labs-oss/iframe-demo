import { ConnectButton } from '@rainbow-me/rainbowkit';
import type { NextPage } from 'next';
import Head from 'next/head';
import Image from 'next/image';
import styles from '../styles/Home.module.css';
import { useState, useEffect } from 'react';

const Home: NextPage = () => {
  useEffect(() => {
    const handleMessage = async (event: MessageEvent) => {
      if (event.data.type === "OPEN_DEEPLINK") {
        if (event.data.link === "") {
          return;
        }

        const isIOS = /iPad|iPhone|iPod/.test(navigator.userAgent);
        const isSafari = /^((?!chrome|android).)*safari/i.test(navigator.userAgent);

        // handle deeplink for iOS Safari
        if (isIOS && isSafari) {
          // href has higher priority than window.open
          window.location.href = event.data.link;
        } else {
          // For other browsers: Use window.open
          window.open(event.data.link, "_blank");
        }
      }
    };

    window.addEventListener("message", handleMessage);
    return () => window.removeEventListener("message", handleMessage);
  }, []);

  return (
    <div className={styles.container}>
      <Head>
        <title>Global wallet demo app</title>
        <meta
          content="Generated by @rainbow-me/create-rainbowkit"
          name="description"
        />
        <link href="/favicon.ico" rel="icon" />
      </Head>

      <main className={styles.main}>
        <div style={{ width: '100%', height: '100vh', display: 'flex', flexDirection: 'column' }}>
          <div style={{ flex: 1 }}>
            <iframe 
              src="https://basic-demo-repo.vercel.app/"
              width="100%"
              height="95%"
              style={{ border: 'none' }}
              title="Dynamic Demo"
            />
          </div>
        </div>
      </main>
    </div>
  );
};

export default Home;
